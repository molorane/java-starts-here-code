package za.co.molorane.javastartshere.ch03;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import za.co.molorane.javastartshere.ch03.lambda.LambdaDeepDive;
import za.co.molorane.javastartshere.ch03.lambda.LambdaDeepDive.OrderPayload;
import za.co.molorane.javastartshere.ch03.lambda.OrderValidator;

import java.util.List;
import java.util.function.BiFunction;
import java.util.function.Predicate;

import static org.assertj.core.api.Assertions.assertThat;

@DisplayName("Chapter 3: Lambda Expressions Deep Dive & JVM Physics")
class LambdaDeepDiveTest {

    @Test
    @DisplayName("Non-capturing lambdas are cached as singletons by the JVM (zero extra heap allocations)")
    void nonCapturingLambdasAreCachedAsSingletons() {
        OrderValidator<String> validator1 = LambdaDeepDive.createNonCapturingValidator();
        OrderValidator<String> validator2 = LambdaDeepDive.createNonCapturingValidator();

        // Both calls return the exact same instance generated by LambdaMetafactory
        assertThat(validator1)
                .isNotNull()
                .isSameAs(validator2);

        assertThat(validator1.validate("Java 25")).isTrue();
        assertThat(validator1.validate("")).isFalse();
    }

    @Test
    @DisplayName("Capturing lambdas require fresh heap allocations to encapsulate closed-over state")
    void capturingLambdasAllocateNewInstances() {
        int threshold = 5;
        OrderValidator<String> validator1 = LambdaDeepDive.createCapturingValidator(threshold);
        OrderValidator<String> validator2 = LambdaDeepDive.createCapturingValidator(threshold);

        // Capturing closures cannot be cached as identical singletons
        assertThat(validator1)
                .isNotNull()
                .isNotSameAs(validator2);

        assertThat(validator1.validate("Modern Java")).isTrue();
        assertThat(validator1.validate("JVM")).isFalse();
    }

    @Test
    @DisplayName("Method References Archetype 1 & 2: Static and Unbound Instance References")
    void shouldExecuteStaticAndUnboundMethodReferences() {
        var cheapOrder = new OrderPayload("ORD-001", "ORD-TECH-BOOK", 49.99);
        var premiumOrder = new OrderPayload("ORD-002", "ORD-ENTERPRISE-KIT", 250.00);
        var invalidSkuOrder = new OrderPayload("ORD-003", "LEGACY-BOOK", 150.00);

        Predicate<OrderPayload> discountFilter = LambdaDeepDive.staticMethodReference();
        Predicate<OrderPayload> skuFilter = LambdaDeepDive.unboundInstanceMethodReference();

        // Static method reference: OrderPayload::isEligibleForDiscount
        assertThat(discountFilter.test(cheapOrder)).isFalse();
        assertThat(discountFilter.test(premiumOrder)).isTrue();

        // Unbound instance method reference: OrderPayload::hasValidSku
        assertThat(skuFilter.test(premiumOrder)).isTrue();
        assertThat(skuFilter.test(invalidSkuOrder)).isFalse();
    }

    @Test
    @DisplayName("Method References Archetype 3 & 4: Bound Instance and Constructor References")
    void shouldExecuteBoundInstanceAndConstructorReferences() {
        OrderValidator<String> baseValidator = s -> s.startsWith("VIP-");
        Predicate<String> boundPredicate = LambdaDeepDive.boundInstanceMethodReference(baseValidator);

        // Bound to a specific instance: baseValidator::validate
        assertThat(boundPredicate.test("VIP-CUSTOMER-99")).isTrue();
        assertThat(boundPredicate.test("GUEST-CUSTOMER-01")).isFalse();

        // Constructor reference simulation via BiFunction factory
        BiFunction<String, Double, OrderPayload> factory = LambdaDeepDive.constructorReference();
        OrderPayload created = factory.apply("ORD-777", 199.99);

        assertThat(created.orderId()).isEqualTo("ORD-777");
        assertThat(created.sku()).isEqualTo("ORD-DEFAULT");
        assertThat(created.amount()).isEqualTo(199.99);
    }

    @Test
    @DisplayName("Functional Interface SAM Contract: Default and Static Methods for Composition")
    void shouldComposeValidatorsUsingDefaultMethods() {
        OrderValidator<String> notNull = OrderValidator.notNull();
        OrderValidator<String> startsWithOrd = s -> s.startsWith("ORD-");
        OrderValidator<String> endsWith2026 = s -> s.endsWith("-2026");

        // Logical AND composition
        OrderValidator<String> combined = notNull.and(startsWithOrd).and(endsWith2026);

        assertThat(combined.validate("ORD-BOOK-2026")).isTrue();
        assertThat(combined.validate("ORD-BOOK-2025")).isFalse();
        assertThat(combined.validate("INVALID-2026")).isFalse();

        // Logical Negation
        OrderValidator<String> notStartingWithOrd = startsWithOrd.negate();
        assertThat(notStartingWithOrd.validate("LEGACY-101")).isTrue();
        assertThat(notStartingWithOrd.validate("ORD-NEW-202")).isFalse();
    }

    @Test
    @DisplayName("Higher-order function pipeline filtering")
    void shouldFilterOrdersThroughHigherOrderPipeline() {
        List<OrderPayload> orders = List.of(
                new OrderPayload("ORD-1", "ORD-ALPHA", 50.0),
                new OrderPayload("ORD-2", "ORD-BETA", 150.0),
                new OrderPayload("ORD-3", "LEGACY-GAMMA", 200.0)
        );

        Predicate<OrderPayload> validAndDiscounted = LambdaDeepDive.staticMethodReference()
                .and(LambdaDeepDive.unboundInstanceMethodReference());

        List<OrderPayload> filtered = LambdaDeepDive.filterOrders(orders, validAndDiscounted);

        assertThat(filtered)
                .hasSize(1)
                .extracting(OrderPayload::orderId)
                .containsExactly("ORD-2");
    }
}
